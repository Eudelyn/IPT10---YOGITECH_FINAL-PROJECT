CREATE TABLE IF NOT EXISTS products (
    id             INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    seller_id      INT UNSIGNED NOT NULL,
    category_id    INT UNSIGNED NOT NULL,
    external_id    INT UNSIGNED NULL COMMENT 'DummyJSON product id when imported',
    source         ENUM('manual','dummyjson') NOT NULL DEFAULT 'manual',
    sku            VARCHAR(60)  NULL,
    name           VARCHAR(180) NOT NULL,
    brand          VARCHAR(80)  NULL,
    description    TEXT NOT NULL,
    price          DECIMAL(12,2) NOT NULL COMMENT 'Selling price in PHP',
    compare_price  DECIMAL(12,2) NULL COMMENT 'Original price in PHP, shown struck through',
    api_price_usd  DECIMAL(10,2) NULL COMMENT 'Original USD price from the API',
    stock          INT UNSIGNED NOT NULL DEFAULT 0,
    thumbnail      VARCHAR(500) NULL,
    images         TEXT NULL COMMENT 'JSON array of image URLs',
    warranty       VARCHAR(120) NULL,
    return_policy  VARCHAR(120) NULL,
    specs          TEXT NULL COMMENT 'JSON object of extra specs',
    rating         DECIMAL(3,2) NOT NULL DEFAULT 0,
    rating_count   INT UNSIGNED NOT NULL DEFAULT 0,
    sold_count     INT UNSIGNED NOT NULL DEFAULT 0,
    status         ENUM('active','draft') NOT NULL DEFAULT 'active',
    created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_products_seller_external (seller_id, external_id),
    INDEX idx_products_category (category_id),
    INDEX idx_products_status_price (status, price),
    CONSTRAINT fk_products_seller   FOREIGN KEY (seller_id)   REFERENCES users(id)      ON DELETE CASCADE,
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
